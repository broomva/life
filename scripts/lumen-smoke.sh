#!/usr/bin/env bash
#
# scripts/lumen-smoke.sh — Lumen Phase α local smoke rig.
#
# Brings up `lifed` (with mock substrate fallback) + `lifegw` (in dev-mode
# accepting `Bearer dev-token-for-{user_id}` shortcut tokens) on localhost
# and tails their logs in parallel. Optionally runs a curl-based schema
# introspection smoke that needs no warp-oss binary.
#
# Usage:
#   ./scripts/lumen-smoke.sh up              # start daemons + tail logs
#   ./scripts/lumen-smoke.sh smoke-curl      # one-shot HTTP smoke (no warp-oss needed)
#   ./scripts/lumen-smoke.sh down            # stop daemons
#   ./scripts/lumen-smoke.sh status          # show PIDs + ports
#
# Prerequisites:
#   - `cargo` on PATH (Rust 1.85+ per workspace rust-version).
#   - openssl on PATH (already used for the dev-tls/ cert pair).
#   - `metal` from Xcode Metal Toolchain is NOT needed by this rig —
#     only the patched `warp-oss` binary needs it. The rig exercises the
#     SERVER side (lifegw + lifed) which is pure Rust.
#
# Layout (under $WORKDIR, default /tmp/lumen-smoke):
#   $WORKDIR/run/life.sock         lifed public-plane UDS
#   $WORKDIR/run/life-admin.sock   lifed admin-plane UDS
#   $WORKDIR/lifed.toml            lifed config (rel-pathed sockets)
#   $WORKDIR/lifegw.toml           lifegw config (rel-pathed UDS upstream)
#   $WORKDIR/lifed.log             lifed stdout/stderr tail
#   $WORKDIR/lifegw.log            lifegw stdout/stderr tail
#   $WORKDIR/lifed.pid             lifed PID
#   $WORKDIR/lifegw.pid            lifegw PID

set -euo pipefail

WORKDIR="${WORKDIR:-/tmp/lumen-smoke}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIFEGW_HTTPS_ADDR="${LIFEGW_HTTPS_ADDR:-127.0.0.1:8443}"
LIFEGW_HTTP_REDIRECT="${LIFEGW_HTTP_REDIRECT:-127.0.0.1:8080}"
DEV_TLS_DIR="${DEV_TLS_DIR:-$REPO_ROOT/crates/life-runtime/lifegw/dev-tls}"

mkdir -p "$WORKDIR/run"

# ── Helpers ──────────────────────────────────────────────────────────────────

log()  { printf '\033[1;36m[lumen-smoke]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[lumen-smoke]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[lumen-smoke]\033[0m %s\n' "$*" >&2; exit 1; }

ensure_dev_tls() {
    if [[ ! -f "$DEV_TLS_DIR/cert.pem" || ! -f "$DEV_TLS_DIR/key.pem" ]]; then
        log "Generating self-signed dev-tls cert at $DEV_TLS_DIR"
        mkdir -p "$DEV_TLS_DIR"
        openssl req -x509 -nodes -newkey rsa:2048 -days 365 \
            -keyout "$DEV_TLS_DIR/key.pem" \
            -out   "$DEV_TLS_DIR/cert.pem" \
            -subj "/CN=localhost" \
            -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" \
            >/dev/null 2>&1
    fi
}

write_lifed_config() {
    cat > "$WORKDIR/lifed.toml" <<EOF
# Auto-generated by lumen-smoke.sh — local-dev paths only.
# This config relocates lifed's default /run/life sockets to $WORKDIR/run/
# so we can run as an unprivileged user.

[public_plane]
unix_socket = "$WORKDIR/run/life.sock"
unix_socket_mode = 0o600
unix_socket_group = ""

[admin_plane]
unix_socket = "$WORKDIR/run/life-admin.sock"
unix_socket_mode = 0o600
unix_socket_group = ""
EOF
}

write_lifegw_config() {
    cat > "$WORKDIR/lifegw.toml" <<EOF
# Auto-generated by lumen-smoke.sh — local-dev paths only.
[tls]
cert_path = "$DEV_TLS_DIR/cert.pem"
key_path  = "$DEV_TLS_DIR/key.pem"
acme_enabled = false

[listen]
https_addr = "$LIFEGW_HTTPS_ADDR"
http_redirect_addr = "$LIFEGW_HTTP_REDIRECT"

[upstream]
lifed_uds_path = "$WORKDIR/run/life.sock"

[auth]
jwks_url = "https://broomva.tech/api/auth/jwks.json"
kms_provider = "dev"
dev_signer_enabled = true
tier1_issuer = "https://broomva.tech"
tier2_issuer = "lifegw"
publish_jwks_path = "$WORKDIR/run/lifegw-jwks.json"

[admin_plane]
unix_socket = "$WORKDIR/run/lifegw-admin.sock"
# Empty group string -> permissive mode (any caller can open admin
# UDS). Acceptable for local dev only; production sets
# unix_socket_group = "life-admin".
EOF
}

wait_for_path() {
    local path="$1" timeout="${2:-30}"
    local start=$SECONDS
    while [[ ! -S "$path" && ! -f "$path" ]]; do
        sleep 0.5
        (( SECONDS - start > timeout )) && return 1
    done
    return 0
}

wait_for_port() {
    local host_port="$1" timeout="${2:-30}"
    local host="${host_port%:*}" port="${host_port##*:}"
    local start=$SECONDS
    while ! nc -z "$host" "$port" 2>/dev/null; do
        sleep 0.5
        (( SECONDS - start > timeout )) && return 1
    done
    return 0
}

# ── Subcommands ──────────────────────────────────────────────────────────────

cmd_up() {
    ensure_dev_tls
    write_lifed_config
    write_lifegw_config

    cmd_down 2>/dev/null || true

    log "Building lifed + lifegw (release-OFF dev build)..."
    (cd "$REPO_ROOT" && cargo build -p lifed -p lifegw 2>&1) | tail -5

    log "Starting lifed (mock fallback) → $WORKDIR/lifed.log"
    (cd "$REPO_ROOT" && \
        LIFED_CONFIG="$WORKDIR/lifed.toml" \
        LIFED_ALLOW_MOCK_FALLBACK=1 \
        nohup cargo run --quiet -p lifed -- daemon --allow-mock-fallback \
            > "$WORKDIR/lifed.log" 2>&1 &
        echo $! > "$WORKDIR/lifed.pid")
    log "  lifed PID = $(cat "$WORKDIR/lifed.pid")"

    log "Waiting for lifed public-plane UDS at $WORKDIR/run/life.sock..."
    if ! wait_for_path "$WORKDIR/run/life.sock" 60; then
        warn "lifed didn't open UDS within 60s; tail of log follows:"
        tail -20 "$WORKDIR/lifed.log" >&2
        die "Abort. (Check $WORKDIR/lifed.log for the real error.)"
    fi
    # The UDS file appearing means the listener is bound, but lifed's
    # tonic accept loop may not be ready for the HTTP/2 SETTINGS frame
    # yet. Give it a moment so lifegw's eager UDS dial in
    # `connect_uds` doesn't race the server-side handshake. ~500ms is
    # plenty empirically; we use 2s as defensive headroom.
    sleep 2

    log "Starting lifegw (dev-mode, dev-signer enabled) → $WORKDIR/lifegw.log"
    (cd "$REPO_ROOT" && \
        LIFEGW_CONFIG="$WORKDIR/lifegw.toml" \
        nohup cargo run --quiet -p lifegw --features dev-mode -- daemon \
            > "$WORKDIR/lifegw.log" 2>&1 &
        echo $! > "$WORKDIR/lifegw.pid")
    log "  lifegw PID = $(cat "$WORKDIR/lifegw.pid")"

    log "Waiting for lifegw to bind $LIFEGW_HTTPS_ADDR..."
    if ! wait_for_port "$LIFEGW_HTTPS_ADDR" 60; then
        warn "lifegw didn't bind within 60s; tail of log follows:"
        tail -20 "$WORKDIR/lifegw.log" >&2
        die "Abort."
    fi

    log "Stack is up."
    log "  lifegw HTTPS  → https://$LIFEGW_HTTPS_ADDR"
    log "  GraphQL POST  → https://$LIFEGW_HTTPS_ADDR/graphql/v2"
    log "  GraphQL WS    → wss://$LIFEGW_HTTPS_ADDR/graphql-ws"
    log "  Dev token     → Bearer dev-token-for-test-user-1"
    log ""
    log "Quick smoke (run in another shell):"
    log "  ./scripts/lumen-smoke.sh smoke-curl"
    log ""
    log "For warp-oss (after Metal Toolchain install + ./apps/warp-oss-patch/apply-patch.sh):"
    log "  WARP_SERVER_ROOT_URL=https://localhost:$LIFEGW_HTTPS_ADDR \\"
    log "  WARP_WS_SERVER_URL=wss://localhost:$LIFEGW_HTTPS_ADDR/graphql-ws \\"
    log "  WARP_AUTH_TOKEN=dev-token-for-test-user-1 \\"
    log "  ./apps/warp-oss-patch/upstream/target/release/warp-oss"
    log ""
    log "Tailing logs (Ctrl-C to detach; daemons keep running):"
    tail -F "$WORKDIR/lifed.log" "$WORKDIR/lifegw.log"
}

cmd_down() {
    for name in lifegw lifed; do
        local pidfile="$WORKDIR/$name.pid"
        if [[ -f "$pidfile" ]]; then
            local pid; pid="$(cat "$pidfile")"
            if kill -0 "$pid" 2>/dev/null; then
                log "Stopping $name (PID $pid)"
                kill "$pid" 2>/dev/null || true
                # Give it a moment to drain.
                for _ in {1..10}; do
                    kill -0 "$pid" 2>/dev/null || break
                    sleep 0.5
                done
                kill -9 "$pid" 2>/dev/null || true
            fi
            rm -f "$pidfile"
        fi
    done
    # Belt + suspenders: also kill any matching cargo run children.
    pkill -f "target/debug/lifed" 2>/dev/null || true
    pkill -f "target/debug/lifegw" 2>/dev/null || true
    log "Stack stopped."
}

cmd_status() {
    for name in lifed lifegw; do
        local pidfile="$WORKDIR/$name.pid"
        if [[ -f "$pidfile" ]]; then
            local pid; pid="$(cat "$pidfile")"
            if kill -0 "$pid" 2>/dev/null; then
                log "$name: RUNNING (PID $pid)"
            else
                warn "$name: pidfile present but process not running"
            fi
        else
            warn "$name: not started"
        fi
    done
    if [[ -S "$WORKDIR/run/life.sock" ]]; then
        log "lifed UDS:    $WORKDIR/run/life.sock (present)"
    else
        warn "lifed UDS not present"
    fi
    if nc -z "${LIFEGW_HTTPS_ADDR%:*}" "${LIFEGW_HTTPS_ADDR##*:}" 2>/dev/null; then
        log "lifegw bind:  $LIFEGW_HTTPS_ADDR (listening)"
    else
        warn "lifegw not bound on $LIFEGW_HTTPS_ADDR"
    fi
}

cmd_smoke_curl() {
    local endpoint="https://$LIFEGW_HTTPS_ADDR/graphql/v2"
    # Tier-2 capability-token dev shortcut: format is
    # `dev-cap-token-for-{aud}/{user_id}` or just
    # `dev-cap-token-for-{user_id}` (defaults to allowed_audiences[0]).
    # Lumen's audience is "lumen" per route.rs's verify_to_claims call.
    local token="dev-cap-token-for-lumen/test-user-1"

    log "Smoke 1/3 — schema introspection"
    log "POST $endpoint"
    local resp
    resp=$(curl --insecure --silent --show-error --max-time 10 \
        -X POST "$endpoint" \
        -H "Authorization: Bearer $token" \
        -H "Content-Type: application/json" \
        --data-raw '{"query":"{ __schema { queryType { name } mutationType { name } subscriptionType { name } } }"}')
    if echo "$resp" | grep -q '"queryType":{"name":"RootQuery"}'; then
        log "  ✓ schema introspection returns RootQuery"
    else
        warn "  ✗ unexpected response:"
        echo "$resp" | head -5 >&2
        return 1
    fi

    log "Smoke 2/3 — Tier-1 op presence on RootMutation"
    resp=$(curl --insecure --silent --show-error --max-time 10 \
        -X POST "$endpoint" \
        -H "Authorization: Bearer $token" \
        -H "Content-Type: application/json" \
        --data-raw '{"query":"{ __type(name: \"RootMutation\") { fields { name } } }"}')
    for op in createAgentTask mintCustomToken updateUserSettings generateDialogue; do
        if echo "$resp" | grep -q "\"name\":\"$op\""; then
            log "  ✓ $op present"
        else
            warn "  ✗ $op missing"
            return 1
        fi
    done

    log "Smoke 3/3 — createAgentTask (real resolver → lifed.Agent.CreateSession via mock fallback)"
    # Real schema: input is CreateAgentTaskInput, requires
    # clientContext + osContext per RequestContext. Output union has
    # `taskId: ID!` and `responseContext: ResponseContext!`.
    resp=$(curl --insecure --silent --show-error --max-time 10 \
        -X POST "$endpoint" \
        -H "Authorization: Bearer $token" \
        -H "Content-Type: application/json" \
        --data-raw '{
            "query":"mutation Smoke($input: CreateAgentTaskInput!, $rc: RequestContext!) { createAgentTask(input: $input, requestContext: $rc) { __typename ... on CreateAgentTaskOutput { taskId } } }",
            "variables": {
                "input": { "prompt": "echo hello", "environmentUid": "ws-test" },
                "rc": {
                    "clientContext": { "version": "lumen-smoke" },
                    "osContext":     { "name": "darwin", "category": "darwin", "version": "0.0" }
                }
            }
        }')
    if echo "$resp" | grep -qE '"__typename":"CreateAgentTaskOutput"|"__typename":"UserFacingError"|"code":"UPSTREAM_ERROR"|"code":"UNAUTHENTICATED"|"code":"INVALID_INPUT"'; then
        log "  ✓ resolver dispatched (response shape recognized)"
        echo "$resp" | head -3
    else
        warn "  ✗ unexpected response:"
        echo "$resp" | head -5 >&2
        return 1
    fi

    log "Curl smoke PASSED — server side is healthy."
}

# ── Dispatch ─────────────────────────────────────────────────────────────────

case "${1:-up}" in
    up)         cmd_up ;;
    down)       cmd_down ;;
    status)     cmd_status ;;
    smoke-curl) cmd_smoke_curl ;;
    *) die "usage: $0 [up|down|status|smoke-curl]" ;;
esac
